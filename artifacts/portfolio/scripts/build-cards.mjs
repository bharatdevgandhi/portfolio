// Turns the Markdown files in content/cards into gallery cards.
//
// Each file is one card: a short header of `key: value` lines between two
// `---` lines, then the story, with `## Heading` starting each chapter.
// See content/cards/_template.md. Files starting with "_" are ignored.
//
// Output: src/v2/cards.generated.ts, which content.ts and chapters.ts read.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const artifactDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cardsDir = path.join(artifactDir, "content", "cards");
const outFile = path.join(artifactDir, "src", "v2", "cards.generated.ts");
const groups = ["work", "project", "education", "teaching"];

export function parseCard(id, text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error(`${id}: the file must start with a header between two --- lines.`);
  const fields = {};
  let list = null;
  for (const raw of match[1].split(/\r?\n/)) {
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    const item = raw.match(/^\s+-\s+(.*)$/);
    if (item && list) { fields[list].push(item[1].trim()); continue; }
    const pair = raw.match(/^([a-z_]+):\s*(.*)$/);
    if (!pair) throw new Error(`${id}: could not read the line "${raw.trim()}".`);
    if (pair[2] === "") { list = pair[1]; fields[list] = []; }
    else { list = null; fields[pair[1]] = pair[2].trim(); }
  }
  if (!fields.title) throw new Error(`${id}: a card needs a title.`);
  const group = fields.group ?? "project";
  if (!groups.includes(group)) throw new Error(`${id}: group must be one of ${groups.join(", ")}.`);
  const split = (value) => (value ? value.split(",").map((part) => part.trim()).filter(Boolean) : []);
  const pairOf = (value, what) => {
    const [left, right] = value.split("|").map((part) => part.trim());
    if (!left || !right) throw new Error(`${id}: write each ${what} as "one thing | the other".`);
    return [left, right];
  };
  const [width, height] = (fields.image_size ?? "1200x1500").split("x").map(Number);
  if (fields.image && !(width > 0 && height > 0)) throw new Error(`${id}: image_size should look like 1200x1500.`);
  const link = fields.link ? pairOf(fields.link, "link") : null;
  const chapters = [];
  for (const block of match[2].split(/^##\s+/m).slice(1)) {
    const [heading, ...rest] = block.split(/\r?\n/);
    const body = rest.join("\n").trim().split(/\n\s*\n/).map((p) => p.replace(/\s+/g, " ").trim()).filter(Boolean).join(" ");
    if (heading.trim() && body) chapters.push({ heading: heading.trim(), body });
  }
  const intro = fields.intro ?? "";
  return {
    entry: {
      id,
      group,
      title: fields.title,
      orgs: split(fields.orgs),
      role: fields.role ?? "",
      dates: fields.dates ?? "",
      place: fields.place ?? "",
      intro,
      summary: [intro, chapters[0]?.body].filter(Boolean).join(" "),
      metrics: (fields.results ?? []).map((line) => { const [value, label] = pairOf(line, "result"); return { value, label }; }),
      shipped: [],
      tags: split(fields.tags),
      cover: fields.image
        ? { kind: "picture", ratio: `${width} / ${height}`, picture: { src: fields.image, alt: fields.image_alt ?? fields.title, caption: "", width, height, single: true } }
        : { kind: "type", line: fields.title, tone: "ink" },
      ...(fields.badge ? { badge: fields.badge } : {}),
      pictures: [],
      ...(link ? { external: { href: link[0], label: link[1] } } : {}),
    },
    chapters,
  };
}

export async function buildCards() {
  await mkdir(cardsDir, { recursive: true });
  const names = (await readdir(cardsDir)).filter((name) => name.endsWith(".md") && !name.startsWith("_")).sort();
  const cards = [];
  for (const name of names) {
    const id = name.replace(/\.md$/, "");
    if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) throw new Error(`${name}: use lower-case letters, numbers and hyphens in the file name.`);
    cards.push(parseCard(id, await readFile(path.join(cardsDir, name), "utf8")));
  }
  const body = `// Generated by scripts/build-cards.mjs from content/cards/*.md. Do not edit.
import type { Entry } from "./content.ts";

export const extraEntries: Entry[] = ${JSON.stringify(cards.map((card) => card.entry), null, 2)};

export const extraChapters: Record<string, { heading: string; body: string }[]> = ${JSON.stringify(
    Object.fromEntries(cards.map((card) => [card.entry.id, card.chapters])), null, 2)};
`;
  await writeFile(outFile, body);
  return cards.map((card) => card.entry.id);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const ids = await buildCards();
  console.log(ids.length ? `Cards from Markdown: ${ids.join(", ")}` : "No Markdown cards yet (content/cards is empty).");
}
